const DICT: Record<UiLang, Dict> = { en, ar, fr, es, de }

interface I18n {
  lang: UiLang
  chosen: boolean
  dir: 'ltr' | 'rtl'
  setLang: (l: UiLang) => void
  t: (key: string) => string
}

export const Ctx = createContext<I18n>({
  lang: 'en',
  chosen: false,
  dir: 'ltr',
  setLang: () => {},
  t: (k) => k,
})

export function isLang(v: string | null): v is UiLang {
  return !!v && UI_LANGS.some((l) => l.code === v)
}

export function translate(lang: UiLang, key: string): string {
  return DICT[lang][key] ?? en[key] ?? key
}

export function useI18n() {
  return useContext(Ctx)
}
